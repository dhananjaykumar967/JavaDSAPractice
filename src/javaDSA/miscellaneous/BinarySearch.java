package javaDSA.miscellaneous;

import java.util.Arrays;

public class BinarySearch {
    public static void main(String[] args) {
        double d[] = new double[5];
        d[0] = 89.7;
        d[2] = 8;
        d[2] = 85;
        for (double i : d) {
            System.out.println(i);
        }
        System.out.println(Arrays.toString(d));
    }
}
